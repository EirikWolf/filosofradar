/**
 * Normaliserer tekst for nøkkel-oppslag
 */
function normalizeKey(str: string): string {
  return str.toLowerCase().replace(/['"«»’]/g, '').trim();
}

/**
 * Henter kuratert manus eller genererer et strukturert 4-slide manus automatisk.
 */
export function getStoryScript(
  philosopherId: string,
  philosopherName: string,
  experiment: ThoughtExperiment,
): StoryScript {
  const normTitle = normalizeKey(experiment.title);
  const directKey = `${philosopherId}:${normTitle}`;

  if (BESPOKE_STORIES[directKey]) {
    return BESPOKE_STORIES[directKey];
  }

  // Søk etter nøkkel som matcher deler av tittelen
  const foundKey = Object.keys(BESPOKE_STORIES).find((k) => {
    if (!k.startsWith(`${philosopherId}:`)) return false;
    const keyTitle = k.split(':')[1];
    return normTitle.includes(keyTitle) || keyTitle.includes(normTitle);
  });

  if (foundKey && BESPOKE_STORIES[foundKey]) {
    return BESPOKE_STORIES[foundKey];
  }

  // Automatisk fallback-generator som strukturerer eksperimentet i 4 faser
  return {
    experimentTitle: experiment.title,
    philosopherName,
    philosopherId,
    image: experiment.image,
    icon: experiment.icon || '💡',
    totalDurationSeconds: 45,
    slides: [
      {
        chapter: 'krok',
        chapterTitle: 'Kroken',
        chapterNumber: 1,
        durationSeconds: 10,
        badge: '🪝 DEL 1 AV 4 // KROKEN',
        headline: experiment.title,
        subheadline: `Et berømt tankeeksperiment fra ${philosopherName}`,
        body: experiment.description,
        highlight: {
          label: 'Utgangspunktet',
          text: 'Se for deg dette scenarioet og hva det utfordrer i vår vante tankegang.',
          icon: experiment.icon || '✦',
        },
      },
      {
        chapter: 'konflikt',
        chapterTitle: 'Konflikten',
        chapterNumber: 2,
        durationSeconds: 12,
        badge: '⚔️ DEL 2 AV 4 // KONFLIKTEN',
        headline: `Hva ville ${philosopherName} vise?`,
        subheadline: 'Filosofiens oppgjør med det selvfølgelige',
        body: `Gjennom dette tankeeksperimentet utfordret ${philosopherName} etablerte sannheter. Eksperimentet tvinger oss til å velge mellom motstridende intuisjoner om virkelighet, etikk eller kunnskap.`,
        highlight: {
          label: 'Kjerneproblemet',
          text: experiment.takeaway,
          icon: '⚖️',
        },
      },
      {
        chapter: 'fasit',
        chapterTitle: 'Eksamens-fasit',
        chapterNumber: 3,
        durationSeconds: 13,
        badge: '💡 DEL 3 AV 4 // EKSAMENS-FASIT',
        headline: 'Kjernebegrepet du må kunne',
        subheadline: 'Viktig poeng for idéhistorisk forståelse og Ex.phil',
        body: experiment.takeaway,
        highlight: {
          label: 'Husk til eksamen',
          text: `Dette eksperimentet er en nøkkel til ${philosopherName}s filosofiske posisjon i idéhistorien.`,
          icon: '🎓',
        },
      },
      {
        chapter: 'refleksjon',
        chapterTitle: 'Refleksjon',
        chapterNumber: 4,
        durationSeconds: 10,
        badge: '❓ DEL 4 AV 4 // DIN TUR',
        headline: 'Hva tenker du?',
        subheadline: 'Filosofi er ikke ferdig tenkt',
        body: `Hva ville du svart om du sto overfor ${experiment.title.toLowerCase()} i dag? Filosofi handler ikke bare om hva fortidens tenkere mente, men om hvordan du selv orienterer deg i verden.`,
        reflectionPrompt: `Hvordan ville du løst dilemmaet i ${experiment.title}?`,
      },
    ],
  };
}
